import {musicAssets} from '../solo-app/music-assets.mjs';
import {test} from 'node:test';
import assert from 'node:assert/strict';
import {createServer} from 'node:http';
import {readFileSync} from 'node:fs';
import {chromium} from 'playwright';
import {createCatalog,maxCardCopies} from '../../../packages/engine/src/index.ts';
import {recommendedOwnedDeck} from '../../../packages/progression.ts';
import {offlineGrowth,readOfflineGrowth} from '../src/offline-growth.ts';
import {loadSoloRelease} from '../../cli/serve-solo-app.mjs';

test('UI preview chooses a save slot first, then uses only that slot cards, decks, ranked checkpoint and progress',{timeout:120000},async t=>{
  const {files}=loadSoloRelease();
  const mime={...Object.fromEntries(musicAssets.map(name=>[name,'audio/mpeg'])),'index.html':'text/html','game.js':'text/javascript','game.css':'text/css','register.js':'text/javascript','sw.js':'text/javascript','manifest.webmanifest':'application/manifest+json','icon-192.png':'image/png','icon-512.png':'image/png'};
  const server=createServer((req,res)=>{
    const url=(req.url??'/').split('?')[0];
    const path=url==='/ui-preview/'?'index.html':url.startsWith('/ui-preview/')?url.slice('/ui-preview/'.length):'index.html';
    if(!Object.hasOwn(mime,path)||!files.has(path)){res.writeHead(404).end();return;}
    const data=files.get(path);
    res.writeHead(200,{'Content-Type':mime[path]});
    res.end(req.method==='HEAD'?undefined:data);
  });
  await new Promise((resolve,reject)=>{server.once('error',reject);server.listen(0,'127.0.0.1',resolve)});
  t.after(()=>new Promise(resolve=>server.close(resolve)));
  const a=server.address();assert.ok(a&&typeof a==='object');
  const dataPath=new URL('../../../data/cards/',import.meta.url);
  const {file}=JSON.parse(readFileSync(new URL('active.json',dataPath),'utf8'));
  const cards=JSON.parse(readFileSync(new URL(file,dataPath),'utf8'));
  const catalog=createCatalog(cards),growth=offlineGrowth(catalog),profile=readOfflineGrowth(undefined,growth).profile;
  const entries=[
    {name:'슬롯1 마법사',deck:recommendedOwnedDeck(catalog,growth,'mage',profile,117)},
    {name:'슬롯2 전사',deck:recommendedOwnedDeck(catalog,growth,'warrior',profile,117)},
  ];
  const browser=await chromium.launch({headless:true,executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH||undefined});
  t.after(()=>browser.close());
  const context=await browser.newContext({viewport:{width:844,height:390},isMobile:true,hasTouch:true});
  await context.addInitScript(({entries})=>{
    localStorage.setItem('card-duel-ui-preview-slot-1:card-duel-saved-decks',JSON.stringify([entries[0],...Array.from({length:9},(_,i)=>({...entries[0],name:'마법사 시험덱 '+(i+2)}))]));
    localStorage.setItem('card-duel-ui-preview-slot-2:card-duel-saved-decks',JSON.stringify([entries[1]]));
  },{entries});
  const page=await context.newPage();
  const errors=[];page.on('pageerror',err=>errors.push(err.message));page.on('dialog',d=>d.accept());
  await page.goto('http://127.0.0.1:'+a.port+'/ui-preview/');
  await page.getByRole('heading',{name:'저장 슬롯을 선택하세요'}).waitFor();
  assert.equal(await page.locator('.slot-entry-card').count(),3);
  assert.equal(await page.getByRole('button',{name:'솔로 랭크 대전 시작'}).count(),0,'cannot play before choosing slot');
  await page.getByRole('button',{name:'슬롯 2 선택',exact:true}).click();
  const homeSlot=page.getByRole('button',{name:'슬롯 선택',exact:true});
  await homeSlot.waitFor();
  assert.equal(await page.locator('.preview-lobby > .app-header').evaluate(el=>getComputedStyle(el).display),'none','the large header is removed');
  await page.getByRole('button',{name:'대전',exact:true}).click();
  assert.equal(await page.getByRole('button',{name:'슬롯 · 성장 · 저장 경기'}).count(),0,'slot management is not on the play screen');
  assert.equal(await page.locator('.play-support > .saved-duel-panel.slot-panel').count(),0,'no old slot panel in the play hub');
  assert.equal(await page.locator('.preview-hero-tile').count(),9,'the nine hero classes occupy the play screen');
  await page.getByRole('button',{name:'전사',exact:true}).click();
  assert.ok(await page.getByRole('button',{name:entries[1].name}).isVisible(),'slot 2 owns its saved warrior deck');
  assert.equal(await page.locator('.preview-deck-grid>*').count(),9);
  assert.equal(await page.locator('.preview-deck-empty').count(),8);
  const tile=page.locator('.preview-deck-grid button').first();
  const colors=locator=>locator.evaluate(el=>{
    const style=getComputedStyle(el);
    return [style.color,style.backgroundColor,style.borderTopColor];
  });
  assert.deepEqual((await colors(page.locator('.preview-deck-empty').first())).slice(1),['rgb(68, 49, 42)','rgb(155, 120, 86)']);
  const singleTile=await tile.boundingBox();
  assert.equal(await page.getByRole('button',{name:entries[0].name}).count(),0,'slot 1 mage deck never leaks into slot 2');
  await page.getByRole('button',{name:entries[1].name}).click();
  assert.equal(await tile.getAttribute('aria-pressed'),'true');
  assert.equal((await colors(tile))[2],'rgb(255, 225, 138)');
  await page.getByRole('button',{name:'선택한 덱으로 대전 시작'}).waitFor();
  assert.equal(await page.getByRole('button',{name:'선택한 덱으로 대전 시작'}).isEnabled(),true,'slot 2 saved deck playable');
  await page.getByRole('button',{name:'선택한 덱으로 대전 시작'}).click();
  await page.getByRole('heading',{name:'첫 손패를 선택하세요'}).waitFor();
  const matchCounts=await page.evaluate(async()=>{
    const count=async name=>{
      const req=indexedDB.open(name,2);
      const db=await new Promise((resolve,reject)=>{req.onsuccess=()=>resolve(req.result);req.onerror=()=>reject(req.error)});
      const n=await new Promise((resolve,reject)=>{const tx=db.transaction('matches','readonly'),all=tx.objectStore('matches').getAll();tx.oncomplete=()=>resolve(all.result.length);tx.onerror=()=>reject(tx.error)});
      db.close();return n;
    };
    return [await count('card-duel-solo-saves-v1-ui-preview'),await count('card-duel-solo-saves-v1-slot-2-ui-preview')];
  });
  assert.deepEqual(matchCounts,[0,1],'a slot 2 match cannot be written into slot 1');
  await page.getByRole('button',{name:'전투 설정'}).click();
  await page.getByRole('button',{name:'저장 후 나가기'}).click();
  await page.getByRole('button',{name:'메인으로'}).click();
  await page.getByRole('button',{name:'슬롯 선택',exact:true}).click();
  assert.equal(await page.locator('.preview-slot-grid>button').count(),3,'slot management shows just 3 choices');
  assert.equal(await page.locator('.slot-management-screen').count(),0,'no XP/progression panels in slot chooser');
  await page.getByRole('button',{name:'슬롯 1',exact:true}).click();
  await page.getByRole('button',{name:'대전',exact:true}).click();
  await page.getByRole('button',{name:'마법사',exact:true}).click();
  assert.ok(await page.getByRole('button',{name:entries[0].name}).isVisible(),'slot 1 saved mage deck available');
  assert.equal(await page.getByRole('button',{name:entries[1].name}).count(),0,'slot 2 warrior deck not visible in slot 1');
  assert.equal(await page.locator('.preview-deck-grid>button').count(),9);
  assert.deepEqual(await colors(page.locator('.preview-deck-grid button').nth(1)),['rgb(255, 243, 215)','rgb(99, 70, 47)','rgb(197, 153, 96)']);
  const multiTile=await page.locator('.preview-deck-grid button').first().boundingBox();
  assert.ok(singleTile&&multiTile);
  assert.deepEqual([multiTile.width,multiTile.height],[singleTile.width,singleTile.height]);
  const previousPage=page.getByRole('button',{name:'이전 덱 페이지'});
  const nextPage=page.getByRole('button',{name:'다음 덱 페이지'});
  assert.equal(await previousPage.isDisabled(),true);
  assert.equal(await nextPage.isEnabled(),true);
  assert.notDeepEqual(await colors(previousPage),await colors(nextPage));
  for(const viewport of [{width:780,height:360},{width:1366,height:768}]){
    await page.setViewportSize(viewport);
    assert.equal(await page.locator('.preview-deck-grid>*').count(),9);
    const grid=await page.locator('.preview-deck-grid').boundingBox();
    assert.ok(grid&&grid.y+grid.height<=viewport.height);
    assert.notDeepEqual(await colors(previousPage),await colors(nextPage));
  }
  await page.setViewportSize({width:844,height:390});
  await nextPage.click();
  assert.equal(await nextPage.isDisabled(),true);
  assert.equal(await previousPage.isEnabled(),true);
  assert.equal(await page.locator('.preview-deck-grid>button').count(),1);
  assert.equal(await page.locator('.preview-deck-empty').count(),8);
  await page.getByRole('button',{name:'이전 덱 페이지'}).click();
  await page.getByRole('button',{name:/새 덱 만들기/}).click();
  await page.getByRole('button',{name:'＋ 새 덱 만들기',exact:true}).click();
  const builder=page.locator('.deck-builder');
  await builder.waitFor();
  assert.equal(await builder.locator('.collection-leaf').count(),2);
  assert.equal(await builder.locator('.collection-item,.collection-blank').count(),8);
  await builder.getByRole('button',{name:'공용',exact:true}).click();
  assert.equal(await builder.locator('.collection-item,.collection-blank').count(),8);
  assert.equal(await builder.getByRole('button',{name:'다음 페이지'}).isEnabled(),true);
  await builder.getByRole('button',{name:'다음 페이지'}).click();
  assert.match(await builder.locator('.book-page-status').textContent(),/^2 \/ /);
  assert.equal(await builder.getByRole('button',{name:'덱 저장',exact:true}).evaluate(button=>getComputedStyle(button).whiteSpace),'nowrap');
  const growthRecord=()=>page.evaluate(async()=>{
    const request=indexedDB.open('card-duel-solo-saves-v1-ui-preview',2);
    const db=await new Promise((resolve,reject)=>{request.onsuccess=()=>resolve(request.result);request.onerror=()=>reject(request.error);});
    try{
      const record=db.transaction('growth','readonly').objectStore('growth').get('player');
      return await new Promise((resolve,reject)=>{record.onsuccess=()=>resolve(record.result);record.onerror=()=>reject(record.error);});
    }finally{db.close();}
  });
  const before=await growthRecord();
  assert.ok(before?.profile);
  await page.getByRole('button',{name:'메인으로'}).click();
  const developer=page.getByRole('button',{name:/개발자 모드/});
  await developer.click();
  await developer.click();
  const count=Object.values(catalog).filter(card=>maxCardCopies(card)>0).length;
  await page.getByText(`덱 구성 카드 ${count}종 전체 해금 · 개발자 모드 전용`).waitFor();
  await page.getByRole('button',{name:'시험 덱 구성'}).click();
  await page.getByRole('button',{name:/마법사/}).first().click();
  assert.equal(await page.getByText(entries[0].name,{exact:true}).count(),0,'player deck library is isolated');
  await page.getByRole('button',{name:'전체 카드 추천 덱 만들기',exact:true}).click();
  await page.locator('.deck-builder .deck-live-count').getByText('30/30',{exact:true}).waitFor();
  const playerDecks=await page.evaluate(()=>localStorage.getItem('card-duel-ui-preview-slot-1:card-duel-saved-decks'));
  await page.getByPlaceholder('저장할 덱 이름').fill('개발자 시험 덱');
  await page.getByRole('button',{name:'덱 저장',exact:true}).click();
  await page.waitForFunction(()=>localStorage.getItem('card-duel-ui-preview-slot-1:developer:card-duel-saved-decks')?.includes('개발자 시험 덱'));
  assert.equal(await page.evaluate(()=>localStorage.getItem('card-duel-ui-preview-slot-1:card-duel-saved-decks')),playerDecks);
  await page.getByRole('button',{name:'메인으로'}).click();
  await page.getByRole('button',{name:'대전',exact:true}).click();
  await page.getByRole('button',{name:'개발자 랭크 시험 시작',exact:true}).click();
  await page.getByRole('heading',{name:'첫 손패를 선택하세요'}).waitFor();
  await page.locator('.mulligan-confirm').click();
  await page.getByRole('button',{name:'전투 설정'}).click();
  await page.getByRole('button',{name:'항복하기',exact:true}).click();
  await page.getByRole('dialog',{name:'대전 결과'}).waitFor();
  assert.deepEqual(await growthRecord(),before,'developer match cannot award progression or alter ownership');
  await page.getByRole('button',{name:'대전 준비로 돌아가기',exact:true}).click();
  await page.getByRole('button',{name:'메인으로'}).click();
  await page.getByRole('button',{name:/개발자 모드/}).first().click();
  await page.getByRole('button',{name:'유저 모드',exact:true}).click();
  assert.equal(await page.getByRole('button',{name:'시험 덱 구성'}).count(),0);
  assert.deepEqual(await growthRecord(),before);
  assert.deepEqual(errors,[]);
  await context.close();
});